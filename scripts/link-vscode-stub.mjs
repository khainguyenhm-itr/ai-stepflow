/**
 * link-vscode-stub.mjs — make the `vscode` bare specifier resolvable inside the extension's
 * unit-test build output, so extension-host modules can be imported by `node --test` without a
 * real VS Code instance.
 *
 * Writes `packages/extension/out-unit/node_modules/vscode/` as a tiny package that re-exports the
 * compiled test stub. Plain module resolution then finds it from `out-unit/src/*.js`, which works
 * for both `require` and `import` — no loader hooks, no flags.
 *
 * Run after `tsc -p packages/extension/test/unit/tsconfig.json`.
 */
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outUnit = path.join(root, 'packages', 'extension', 'out-unit');
const stub = path.join(outUnit, 'test', 'unit', 'vscodeStub.js');

if (!existsSync(stub)) {
  console.error(`link-vscode-stub: compiled stub not found at ${stub} — run the unit-test compile first.`);
  process.exit(1);
}

const pkgDir = path.join(outUnit, 'node_modules', 'vscode');
mkdirSync(pkgDir, { recursive: true });
writeFileSync(
  path.join(pkgDir, 'package.json'),
  JSON.stringify({ name: 'vscode', version: '0.0.0-test-stub', main: 'index.js' }, null, 2) + '\n',
  'utf8'
);
writeFileSync(
  path.join(pkgDir, 'index.js'),
  '// Generated by scripts/link-vscode-stub.mjs — re-exports the compiled unit-test vscode stub.\n' +
  "module.exports = require('../../test/unit/vscodeStub.js');\n",
  'utf8'
);

console.log('vscode test stub linked into out-unit.');
